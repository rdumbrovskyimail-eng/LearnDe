package com.learnde.app.learn.domain.v2

import javax.inject.Inject
import javax.inject.Singleton

enum class PaceLevel(
    /** Сколько секунд живёт «заявленное» моделью отступление (flex_moment). */
    val digressionBudgetSec: Int,
) {
    /** Максимум кайфа: длинные отступления, редкие напоминания. */
    RELAXED(180),

    /** Баланс: поболтали пару минут — мягко вернулись. */
    NORMAL(105),

    /** Слепой режим / марафон: отступления короче, темп ровнее. */
    FOCUSED(60);
}

@Singleton
class FlexTalkPolicy @Inject constructor() {

    @Volatile var pace: PaceLevel = PaceLevel.NORMAL

    val digressionBudgetMs: Long
        get() = pace.digressionBudgetSec * 1000L

    /**
     * Мягкое напоминание модели. Уровень 0 — почти невидимое,
     * уровень 1 — чуть настойчивее. Оба требуют ЕСТЕСТВЕННОГО
     * перехода — без «так, хватит болтать».
     */
    fun softReminder(step: LessonStep, level: Int): String = when (level) {
        0 -> "[СИСТЕМА]: Разговор затянулся — это нормально. Когда будет " +
            "естественная пауза, плавно (одним мостиком-фразой) вернись к " +
            "текущему шагу ${step.id} (${step.kind.name}" +
            (step.lemma?.let { ", слово «$it»" } ?: "") + "). Не извиняйся, " +
            "не упоминай систему."

        else -> "[СИСТЕМА]: Пора вернуться к графику. Заверши текущую мысль " +
            "одной фразой и сразу выполни шаг ${step.id}" +
            (step.lemma?.let { " (слово «$it»)" } ?: "") + ". Сделай переход " +
            "тёплым: «кстати, вернёмся к нашему слову…»."
    }

    /**
     * Фраза-мостик, когда ученик долго молчит (передаётся вместо
     * жёсткого «Ученик молчит» из v3.x).
     */
    fun silenceNudge(step: LessonStep?): String =
        "[СИСТЕМА]: Ученик молчит. Без упрёка: подбодри одной короткой " +
        "фразой по-русски и дай подсказку" +
        (step?.lemma?.let { " к слову «$it» (первый слог или ЕГО ассоциация)" } ?: "") +
        ". Если молчание повторится — назови ответ сам и попроси повторить."
}